def build_slice_index(patient_list, config):
    index = []
    for p in patient_list:
        seg_img = nib.load(p[config["seg_suffix"]])
        depth = seg_img.shape[2]
        margin = config["slice_margin"]
        lo, hi = margin, depth - margin
        if hi <= lo:
            print(f"⚠️ {p['patient_id']}: depth {depth} too small for margin {margin}, skipping")
            continue
        for s in range(lo, hi):
            index.append({**p, "slice_idx": s})
    return index

