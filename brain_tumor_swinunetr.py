import cv2

def remap_mask(mask):
    remapped = np.zeros_like(mask, dtype=np.int64)
    remapped[mask == 1] = 1
    remapped[mask == 2] = 2
    remapped[mask == 4] = 3
    return remapped

def normalize_slice(img):
    img = img.astype(np.float32)
    nz = img[img > 0]
    if nz.size > 0:
        mean, std = nz.mean(), nz.std() + 1e-8
        img = (img - mean) / std
    img = np.clip(img, -5, 5)
    img = (img - img.min()) / (img.max() - img.min() + 1e-8)
    return img

def resize_arr(arr, size, is_mask=False):
    interp = cv2.INTER_NEAREST if is_mask else cv2.INTER_LINEAR
    return cv2.resize(arr.astype(np.float32), (size, size), interpolation=interp)

