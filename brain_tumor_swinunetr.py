def one_hot(labels, num_classes):
    return F.one_hot(labels, num_classes).permute(0, 3, 1, 2).float()

def compute_metrics(pred_logits, labels, num_classes):
    pred = torch.argmax(pred_logits, dim=1)
    pred_oh = one_hot(pred, num_classes)
    label_oh = one_hot(labels, num_classes)
    dice_metric(y_pred=pred_oh, y=label_oh)
    iou_metric(y_pred=pred_oh, y=label_oh)
    cm_metric(y_pred=pred_oh, y=label_oh)

def accuracy_from_logits(pred_logits, labels):
    pred = torch.argmax(pred_logits, dim=1)
    correct = (pred == labels).sum().item()
    total = labels.numel()
    return correct, total

def aggregate_reset(*metrics):
    results = [m.aggregate() for m in metrics]
    for m in metrics:
        m.reset()
    return results

