def match_modality_files(patient_dir, config):
    files = [f for f in os.listdir(patient_dir) if f.endswith(".nii") or f.endswith(".nii.gz")]
    found = {}
    for key in config["modalities"] + [config["seg_suffix"]]:
        pattern = re.compile(rf"_{key}\.nii(\.gz)?$", re.IGNORECASE)
        matches = [f for f in files if pattern.search(f)]
        if not matches:
            matches = [f for f in files if f.lower().startswith(key.lower())]
        found[key] = os.path.join(patient_dir, matches[0]) if matches else None
    return found

