class FastSliceDataset(Dataset):
    def __init__(self, manifest, transforms=None):
        self.manifest = manifest
        self.transforms = transforms

    def __len__(self):
        return len(self.manifest)

    def __getitem__(self, idx):
        rec = self.manifest[idx]
        data = np.load(rec["path"])
        image = torch.from_numpy(data["image"].astype(np.float32))
        label = torch.from_numpy(data["label"].astype(np.int64)).unsqueeze(0)

        sample = {"image": image, "label": label}
        if self.transforms:
            sample = self.transforms(sample)

        sample["label"] = sample["label"].squeeze(0)
        sample["patient_id"] = rec["patient_id"]
        sample["slice_idx"] = rec["slice_idx"]
        return sample

