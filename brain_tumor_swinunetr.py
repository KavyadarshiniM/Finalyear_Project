mask_colors = ["#0b1547", "#f4d35e", "#4fc3d9", "#e63946"]
mask_cmap = mcolors.ListedColormap(mask_colors)
mask_norm = mcolors.BoundaryNorm(boundaries=[-0.5, 0.5, 1.5, 2.5, 3.5], ncolors=4)

def pick_sample_indices(dataset, num_tumor=2, num_background=1):
    tumor_idx, bg_idx = [], []
    indices = list(range(len(dataset)))
    random.shuffle(indices)
    for i in indices:
        rec = dataset.manifest[i]
        data = np.load(rec["path"])
        if (data["label"] > 0).any():
            if len(tumor_idx) < num_tumor:
                tumor_idx.append(i)
        else:
            if len(bg_idx) < num_background:
                bg_idx.append(i)
        if len(tumor_idx) >= num_tumor and len(bg_idx) >= num_background:
            break
    return tumor_idx + bg_idx

