def preprocess_split(slice_list, split_name, config):
    out_dir = os.path.join(PREPROC_DIR, split_name)
    os.makedirs(out_dir, exist_ok=True)
    manifest = []

    cur_pid = None
    stack = None
    seg = None

    for rec in tqdm(slice_list, desc=f"Preprocessing {split_name}"):
        pid, s = rec["patient_id"], rec["slice_idx"]

        if pid != cur_pid:
            mods = [nib.load(rec[m]).get_fdata() for m in config["modalities"]]
            seg = nib.load(rec[config["seg_suffix"]]).get_fdata()
            stack = np.stack(mods, axis=0)
            cur_pid = pid

        img_slice = stack[:, :, :, s]
        mask_slice = remap_mask(seg[:, :, s])

        size = config["img_size"]
        img_slice = np.stack(
            [resize_arr(normalize_slice(img_slice[c]), size) for c in range(img_slice.shape[0])],
            axis=0
        ).astype(np.float16)
        mask_slice = resize_arr(mask_slice.astype(np.float32), size, is_mask=True).astype(np.uint8)

        fname = f"{pid}_slice{s:04d}.npz"
        fpath = os.path.join(out_dir, fname)
        np.savez(fpath, image=img_slice, label=mask_slice)
        manifest.append({"patient_id": pid, "slice_idx": s, "path": fpath})

    return manifest

